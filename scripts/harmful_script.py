"""Prototype harmful script that appends entries to `logs/monitor.log`.

Run this in a terminal to simulate an attack event being generated by a host or
network sensor. The monitor will pick it up and trigger anomaly detection.
"""
import time
import os

LOG_PATH = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'logs', 'monitor.log')


def ensure_log():
    basedir = os.path.dirname(LOG_PATH)
    os.makedirs(basedir, exist_ok=True)
    if not os.path.exists(LOG_PATH):
        open(LOG_PATH, 'a').close()


def emit_malicious_events(count: int = 2, interval: float = 1.0):
    ensure_log()
    with open(LOG_PATH, 'a', encoding='utf-8') as fh:
        for i in range(count):
            fh.write(f"{time.strftime('%Y-%m-%d %H:%M:%S')} - MALICIOUS - simulated attack event {i+1}\n")
            fh.flush()
            print(f"Wrote malicious event {i+1}")
            time.sleep(interval)


if __name__ == '__main__':
    print("Starting harmful script to emit simulated malicious events")
    emit_malicious_events()
